pub(super) fn alphabet(source: &str, name: &str) -> String {
    let (uppercase, lowercase, digits, special): (u32, u32, u32, &[(char, char)]) = match name {
        "mathbf" => (0x1d400, 0x1d41a, 0x1d7ce, &[]),
        "mathcal" => (
            0x1d49c,
            0x1d4b6,
            0,
            &[
                ('B', 'ℬ'),
                ('E', 'ℰ'),
                ('F', 'ℱ'),
                ('H', 'ℋ'),
                ('I', 'ℐ'),
                ('L', 'ℒ'),
                ('M', 'ℳ'),
                ('R', 'ℛ'),
                ('e', 'ℯ'),
                ('g', 'ℊ'),
                ('o', 'ℴ'),
            ],
        ),
        "mathbb" => (
            0x1d538,
            0x1d552,
            0x1d7d8,
            &[
                ('C', 'ℂ'),
                ('H', 'ℍ'),
                ('N', 'ℕ'),
                ('P', 'ℙ'),
                ('Q', 'ℚ'),
                ('R', 'ℝ'),
                ('Z', 'ℤ'),
            ],
        ),
        "mathfrak" => (
            0x1d504,
            0x1d51e,
            0,
            &[('C', 'ℭ'), ('H', 'ℌ'), ('I', 'ℑ'), ('R', 'ℜ'), ('Z', 'ℨ')],
        ),
        "mathit" => (0x1d434, 0x1d44e, 0, &[('h', 'ℎ')]),
        "mathsf" => (0x1d5a0, 0x1d5ba, 0x1d7e2, &[]),
        "mathtt" => (0x1d670, 0x1d68a, 0x1d7f6, &[]),
        _ => return source.into(),
    };
    source
        .chars()
        .map(|character| {
            if let Some((_, replacement)) =
                special.iter().find(|(original, _)| *original == character)
            {
                return *replacement;
            }
            let (base, offset) = match character {
                'A'..='Z' => (uppercase, character as u32 - 'A' as u32),
                'a'..='z' => (lowercase, character as u32 - 'a' as u32),
                '0'..='9' => (digits, character as u32 - '0' as u32),
                _ => (0, 0),
            };
            if base == 0 {
                character
            } else {
                char::from_u32(base + offset).unwrap_or(character)
            }
        })
        .collect()
}
