use super::{
    FontExtents, FontVariant, MeasurementError, TextMeasurement, measured_size, prepare_text,
};

/// Standard PDF font metrics using the WinAnsi character repertoire.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CoreFont {
    Helvetica,
    Times,
    Courier,
}

impl CoreFont {
    pub fn family(self) -> &'static str {
        match self {
            Self::Helvetica => "Helvetica",
            Self::Times => "Times",
            Self::Courier => "Courier",
        }
    }

    pub fn measure(
        self,
        text: &str,
        size_points: f64,
        variant: FontVariant,
    ) -> Result<TextMeasurement, MeasurementError> {
        let size_points = measured_size(size_points)?;
        let widths = match (self, variant) {
            (Self::Courier, _) => &[600; 256],
            (Self::Times, FontVariant::Bold) => &TIMES_BOLD,
            (Self::Times, FontVariant::Italic) => &TIMES_ITALIC,
            (Self::Times, FontVariant::BoldItalic) => &TIMES_BOLD_ITALIC,
            (Self::Times, _) => &TIMES,
            (Self::Helvetica, FontVariant::Bold | FontVariant::BoldItalic) => &HELVETICA_BOLD,
            (Self::Helvetica, _) => &HELVETICA,
        };
        let (prepared_text, missing_codepoints) = prepare_text(text, |character| {
            win_ansi(character).is_some_and(|encoded| widths[usize::from(encoded)] > 0)
        });
        let units: u64 = prepared_text
            .chars()
            .map(|character| {
                u64::from(
                    widths[usize::from(win_ansi(character).expect("prepared core character"))],
                )
            })
            .sum();
        let width = units as f64 * size_points / 1000.0;
        let (ascent, descent) = match self {
            Self::Helvetica => (718.0, 207.0),
            Self::Times => (683.0, 217.0),
            Self::Courier => (629.0, 157.0),
        };
        Ok(TextMeasurement {
            prepared_text,
            missing_codepoints,
            layout_width: width,
            paint_width: width,
            extents: FontExtents {
                ascent: ascent * size_points / 1000.0,
                descent: descent * size_points / 1000.0,
                height: (ascent + descent) * size_points / 1000.0,
            },
        })
    }
}

fn win_ansi(character: char) -> Option<u8> {
    match character {
        ' '..='~' | '\u{a0}'..='\u{ff}' => Some(character as u8),
        '€' => Some(0x80),
        '‚' => Some(0x82),
        'ƒ' => Some(0x83),
        '„' => Some(0x84),
        '…' => Some(0x85),
        '†' => Some(0x86),
        '‡' => Some(0x87),
        'ˆ' => Some(0x88),
        '‰' => Some(0x89),
        'Š' => Some(0x8a),
        '‹' => Some(0x8b),
        'Œ' => Some(0x8c),
        'Ž' => Some(0x8e),
        '‘' => Some(0x91),
        '’' => Some(0x92),
        '“' => Some(0x93),
        '”' => Some(0x94),
        '•' => Some(0x95),
        '–' => Some(0x96),
        '—' => Some(0x97),
        '˜' => Some(0x98),
        '™' => Some(0x99),
        'š' => Some(0x9a),
        '›' => Some(0x9b),
        'œ' => Some(0x9c),
        'ž' => Some(0x9e),
        'Ÿ' => Some(0x9f),
        _ => None,
    }
}

